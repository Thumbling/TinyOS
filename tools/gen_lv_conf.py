def set_define(text: str, name: str, value: str) -> str:
    pattern = re.compile(rf"^#define\s+{re.escape(name)}\s+.*$", re.MULTILINE)
    replacement = f"#define {name} {value}"
    if pattern.search(text):
        return pattern.sub(replacement, text, count=1)
    # Insert after the first configuration block marker if the template has no
    # such symbol in this release.
    marker = "/*=====================\n * MEMORY"
    if marker in text:
        return text.replace(marker, f"{replacement}\n\n{marker}", 1)
    return text


def main() -> None:
    if not TEMPLATE.exists():
        raise SystemExit(f"missing {TEMPLATE}; run tools/fetch-lvgl.sh first")
    text = TEMPLATE.read_text(encoding="utf-8")
    text = text.replace(
        '#if 0 /* Set this to "1" to enable content */',
        '#if 1 /* TinyOS: generated by tools/gen_lv_conf.py */',
        1,
    )
    for name, value in OVERRIDES.items():
        text = set_define(text, name, value)
    text = "/* Generated by tools/gen_lv_conf.py. Do not edit by hand. */\n" + text
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
